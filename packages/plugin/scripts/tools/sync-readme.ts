/** GitHub README 是核心介绍的唯一来源；npm 使用公开链接。 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const packageRoot = resolve(import.meta.dirname, '../..');
const repo = resolve(packageRoot, '../..');
const version = (JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8')) as { version: string }).version;
const source = readFileSync(resolve(repo, 'README.md'), 'utf8');
const readme = source.replace(/\]\(([^)\s]+)\)/g, (match: string, target: string): string => {
  if (/^(https?:|#|mailto:)/.test(target)) return match;
  const base = /\.(png|jpg|jpeg|webp|svg)$/.test(target)
    ? 'https://raw.githubusercontent.com/Luan-Fuzi/foldercast'
    : 'https://github.com/Luan-Fuzi/foldercast/blob';
  return `](${base}/v${version}/${target})`;
});
writeFileSync(resolve(packageRoot, 'README.md'), `<!-- Generated by scripts/tools/sync-readme.ts; edit the repository README.md. -->\n${readme}`);
for (const name of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) {
  writeFileSync(resolve(packageRoot, name), readFileSync(resolve(repo, name)));
}
