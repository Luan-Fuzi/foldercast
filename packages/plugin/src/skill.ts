export const SKILL_CONTENT = `# 目录放映（foldercast）

把任意**人类可读的目录**变成讲解视频。核心产物不是视频，而是「目录解读」这份结构化事实；
视频、页面都是它的视图。

## 什么时候用

用户要求讲解、导览、介绍某个目录（项目、资料、汇报文件夹都算）。**输入只有目录路径**，
不需要风格、时长之类的参数——第一版没有可配置项。

## 工作流

六步：跑事实层 → 通读 → 定场景 → 写稿 → 校验 → 评审 →（要成片时）配音与出片。
**通读与评审这两步不能省**，省了就会写成「这个目录分成三部分，第一部分是源码」这种正确的废话。

### 第一步：跑事实层

调 \`foldercast_cast\`，参数是目录的**绝对路径**。它做两件事（都是确定性程序）：

1. **分析**：遍历目录 → \`<目录>/.foldercast/foldercast.json\`。里面**只有机械事实**：
   每条文件的路径、类别（12 类）、字节、行数、截断预览，外加密钥排除审计。
2. **素材**（默认跑，可用 \`skipAssets\` 跳过）：解读里的图片 / 视频 / Office / PDF →
   \`<目录>/.foldercast/assets/\`（缩略图、关键帧、逐页图、提取出的全文 Markdown）。

有讲稿时它顺带跑一次校验。**渲染与配音不自动跑**（一次要几分钟到几十分钟、配音还会消耗
TTS 配额）：要成片就再调一次并显式传 \`render: true\`（要先配音就同时传 \`voice: true\`）。

看返回值：\`artifacts\` 是**磁盘上现在有什么** —— 解读、素材清单、讲稿、评审、时长表、旁白音轨、
成片，每个带 \`state\`（\`missing\` 没有 / \`stale\` 有但比讲稿旧 / \`fresh\` 有且不旧）
与 \`path\`；\`ran\` 是这次实际跑了哪些阶段；\`reading.droppedByMaxFiles\` 与
\`reading.skippedForSize\` 告诉你这份解读**有没有漏掉文件**（非 0 就见第二条的说明）；
\`validation.issues\` 每条都带文件、行号、场景 id 与怎么改；
\`dependencies\` 只列**不可用**的依赖，都正常时是空数组。
**「下一步该做什么」不在返回值里**：那是这份说明与你的判断。

### 第二步：通读内容

摘要里没有语义。只看「74 个 TS 文件、最大 2048 字节」，写出来的只能是正确的废话——
对代码项目勉强够用，对混杂资料目录完全失效。

**读什么**（按这个顺序）：

1. \`<目录>/.foldercast/foldercast.json\` —— 先读 \`stats\`（总数、类型分布、被排除的密钥文件名），
   再读 \`manifest\`。**\`preview\` 是每条文件唯一的语义线索**（标题、首段或首个注释的截断），
   靠它判断「哪些值得展开读全文」。
2. **自己判断重点，程序不给排名**。解读里没有「入口」「枢纽」「角色」这类字段——那些要
   读内容才知道，所以由你判断。常用的机械依据：\`preview\` 的内容、文件路径与命名、
   \`lines\` 与 \`bytes\`（大文件通常承载更多信息）、同一目录下的文件成组出现。
3. **全文读**：上一步挑出来的重点文件，以及顶层说明文件（README、索引、清单类）。
4. Office / PDF 的全文在 \`<目录>/.foldercast/assets/text/*.md\`（素材阶段提取的），
   要讲它们就先把这几份读了；图片/视频看 \`assets/manifest.json\` 知道有哪些画面可用。
5. **注意漏读的边界**：\`reading.droppedByMaxFiles > 0\` 时解读只覆盖了一部分文件。
   这时**必须**去看被丢掉的是什么（\`sources.maxFiles\` 是上限值），或者在讲稿里说明
   「这个目录还有 N 个文件没有进来」。\`skippedForSize > 0\` 时同理（那几个文件没有 \`preview\`）。

**大目录（文件数超过 50）用 subagent 分工读**：每个 subagent 负责一块（一个子目录），
回来只汇报三件事 —— 「这块是什么」「有哪些值得讲的」「有没有出乎意料的东西」。
分完工你自己再读一遍最顶层的那几个文件，别全交出去。

**开不出 subagent 时**（子 agent 有深度上限，被委派的写手往往已经在最后一层）：
先全量过一遍 \`manifest\` 的 \`preview\` 与 \`stats\`，再挑重点文件读全文。
目标与分工读一样 —— 别因为开不出 subagent 就跳过通读。

**读完先写一份叙事大纲，再动笔**：3–6 条要点，每条对应「观众需要知道的一件事」。
写不出大纲说明还没读懂，回去读，不要直接开始填场景。

### 第三步：定场景计划

先想清楚「观众按这个顺序看下来，能不能明白这个目录是干什么的」，再选场景类型。

| type | 什么时候用 | 必需字段 |
|---|---|---|
| \`cover\` | 开头，一个场景 | \`title\`（**人话名称**，不是路径） |
| \`tree\` | 让人一眼看到目录结构 | \`highlight\`（2–4 个真正重要的子路径） |
| \`inventory\` | 盘点内容构成 | \`groups\`（每项 \`kind\` + \`count\`，取自解读的 \`stats.kindCounts\`） |
| \`file\` | 讲某个具体文件 | \`file\`（相对源目录，必须在 manifest 里） |
| \`gallery\` | 展示一组图片 | \`items\`（素材路径，相对工作根） |
| \`clip\` | 讲一段视频（**画面是封面图，不播活动画面**） | \`source\`（相对源目录） |
| \`document\` | 翻 Office / PDF 的页 | \`source\` + \`pages\`（素材路径） |
| \`outro\` | 结尾，一个场景 | \`title\` |

**选择判据**：

- **有具体文件可指，就用 \`file\`**。空泛的概括不如指出「\`src/Root.tsx\` 注册了全部 7 个合成入口」。
- **讲整体构成用 \`inventory\`，讲结构用 \`tree\`**，两者不要互相代替：tree 只有路径，inventory 只有数量。
- **素材里有图就考虑 \`gallery\`**，有 Office/PDF 且值得翻页就用 \`document\`。没有素材就不要编。
- **\`clip\` 的画面是封面图**（第一版不播活动画面，渲染层读不了本地视频）。所以讲视频时
  别说「接下来播放这段」——说「这是它的封面」或直接讲内容；\`clipRange\` 仍然有用，它会被
  标在画面上，配音（M8）也可以按它取音。
- **顺序**：\`cover\` → \`tree\` → \`inventory\` → 若干 \`file\` / \`gallery\` / \`document\` / \`clip\` → \`outro\`。
  中间部分的顺序按「观众要先知道什么」排：先整体构成、再关键文件、最后细节。
  **不要在稿子里暴露你猜的过程**（「我判断」「可能」），讲出来的话要像事实。
- **规模**：整片 8–15 个场景（上千文件的大目录可以到 20 —— 上限是节奏建议，不是内容上限）。
  一个场景的 \`narration\` 以 1–3 句、40–80 字为主（约 10–20 秒）；**超过约 120 字说明这场塞了
  两件事，拆开**，不要靠硬压字数。反过来，若拆到没内容可讲，那说明该压缩而不是该拆。

### 第四步：写讲稿

写到 \`<目录>/.foldercast/script.json\`，形状见 \`docs/specs/script.schema.json\`。

- 顶层：\`foldercast: 1\`、\`source.root\`（**必须等于解读里的 \`source.root\`**）、\`scenes\`
- 场景：\`id\`（唯一，短横线命名如 \`hub-components\`）、\`type\`、\`narration\`，加该类型的必需字段
- 可选字段按需用：\`title\`、\`subtitle\`、\`asset\`（file 场景的配图，用来补一张页图或缩略图）、
  \`poster\` 与 \`clipRange\`（clip 场景的封面与片段区间）
- **路径两条基准不能混**：\`file\` / \`source\` 相对**源目录**；\`asset\` / \`items\` / \`poster\` / \`pages\`
  相对**工作根** \`.foldercast/\`，所以它们以 \`assets/\` 开头
- **不能编路径**。引用前先确认它在解读的 \`manifest\` 或素材清单里；校验器会逐条拦

**\`narration\` 是念出来的话，不是写出来的报告**：

- 口语、短句、能直接读。「这个目录里有 94 个文件，其中 68 个是音频」比「文件构成呈现音频主导特征」好
- 具体优于概括：给出文件名、数字、位置，而不是「多个文件」「若干模块」
- 不写「让我们一起来看看」「综上所述」这类过场话
- 数字可以说约数（「大约七十个音频」），但路径与事实不能含糊

**字幕切分**：「\`narration\` 要能切成每块 ≤24 个**显示宽度**的字幕块（中日韩字符算 1，
其余算 0.5，所以 24 个汉字或 48 个英文字母）。切法：先按句末标点（\`。！？；：\`）切，
超长的在逗号（\`，、\`）处再切。**一句里没有任何标点又超过 24 宽度，就切不开，校验会报错**——
加标点或拆句。这也是为什么 narration 要写成短句。

### 第五步：校验并修

再调一次 \`foldercast_cast\`。它跑校验器，返回 \`ok\` 与每条问题（带文件名、行号、场景 id）。
**有 blocker 就不要往下走**：那是编造路径、场景字段用错、字幕切不开这类硬错误。
warning 是「可能是笔误」，自己判断要不要改。

### 第七步：出片

评审通过之后再调一次 \`foldercast_cast\`：它这次会跑渲染，产出
\`<目录>/.foldercast/out/video.mp4\`（静音，1920×1080，30fps）。**渲染慢**：本机实测约
7 帧/秒，5 分钟的片子要 20 分钟出头，所以不要为了看一眼就整片重渲 —— 调画面用
\`pnpm render <目录> --still <秒>\` 出一张静帧，或 \`--frames A-B\` 出一小段。

**没有浏览器时**（\`next: blocked\`，引导里写着三种办法）：不要自己去下载几百 MB 的东西，
把引导转告用户，让他决定装 Chrome 还是跑 \`npx remotion browser ensure\`。
缺浏览器只影响出片，解读、素材、页面、校验都照常可用。

**画面来自讲稿，不是自动生成的**：每个场景按 \`type\` 决定版式，讲稿里写的 \`title\` 是画面上的
标题，\`narration\` 是底部字幕（按第四步的规则切成块），\`file\` / \`items\` / \`pages\` 决定中间
放哪张素材。所以「画面不对」通常要改讲稿，而不是改渲染器。

**时长由字数估**（中文约 4.3 字/秒 + 每场景留白）：讲稿里写了 \`video.targetDurationSec\`
就按比例缩放各场景时长（软约束，不截断文案）。配音阶段（M8）会用实测音频时长重渲一遍。

**改讲稿之后就 \`video\` 变 \`stale\`**，再调一次工具会重渲（旧成片被覆盖）。**没改讲稿不会重渲** ——
所以反复调工具不会反复花那几十分钟。

### 第六步：评审（起独立 subagent）

**必须换一条上下文**：自己审自己会为已经做过的选择辩护。起一个 subagent，输入只有三样：

- 解读的路径 \`<目录>/.foldercast/foldercast.json\`
- 讲稿的路径 \`<目录>/.foldercast/script.json\`
- 被讲解目录的路径（只读，用来核对事实）

**不要把写稿时的理由、大纲、或「我觉得哪里不太行」告诉它** —— 那会污染结论。
把下面「评审判据」整节交给它，让它按判据逐条给结论。

评审结果写到 \`<目录>/.foldercast/review.md\`，格式：

\`\`\`markdown
# 评审：<目录名>

结论：通过 / 不通过

## 1. 编造
结论：无 / 有（列出场景 id）
证据：<场景 id> 说「…」，在 <文件路径> 第 N 行找到依据 / 找不到依据

## 2. 重点
…
\`\`\`

**每一条都必须给证据**（文件路径、原文片段、行号）。评审 agent 自己也会错，没有证据的结论
没法抽查，等于没审。

## 评审判据

给评审 subagent 的判据。逐条给「结论 + 证据」，不许只写一句「整体不错」。

1. **编造**：讲稿里每个事实性断言，都要能在被讲解目录里找到依据。逐个断言核对，
   引用文件路径与原文片段；找不到依据的列出来。**这是最严重的一条**，有一条就是「不通过」。
2. **重点**：解读里体积最大、行数最多、以及顶层说明类的文件，讲到了哪些、没讲到哪些。
   **解读不提供「哪个重要」的排名**（那是写稿人读内容后自己判断的），所以这一条要问的是：
   写稿人挑的重点，与你自己读完目录后的判断是否一致；差得远就列出分歧点与依据。
3. **遗漏**：有没有「看了目录的人会觉得奇怪」的缺失——最大的那个目录没提、占比最高的类型没提、
   密钥类文件被排除这件事没跟用户说（\`stats.secrets.excluded\` 非空时必须提一句）。
4. **结构与顺序**：场景顺序是否合乎阅读顺序（整体构成 → 关键文件 → 细节），
   \`cover\` / \`outro\` 是否名副其实，有没有该拆的场景（一个场景塞了多个主题）。
5. **语言**：是不是口语（能直接念出来），有没有空泛套话，数字与路径是否具体。
6. **边界**：有没有猜测密钥文件的内容（\`stats.secrets\` 只按文件名命中，内容从未读入）；
   有没有把「解读只覆盖了一部分文件」说成「这就是全部」（看 \`droppedByMaxFiles\`）。

**结论只有两种**：有一条编造 → 不通过；其余条目可以带「建议」通过，但要写清哪里可以更好。
不确定的写「待确认」并说明缺什么证据，**不要猜**。

## 判据（写稿时别糊弄自己）

- **解读是事实**：\`stats\` 与 \`manifest\` 由程序产出，不要凭印象改数字
- **讲稿是创作**：可以有观点，但**不能编事实**。说「这个项目用 Remotion 渲染」之前，
  先确认你在内容里看到了它
- **密钥文件的内容没被读过**：\`reading.secretsSkipped\` 列出的文件名只是文件名命中，
  内容从未读入。可以向用户提一句「这些文件被跳过了」，但不要猜里面是什么
- **页数是弱证据**：素材清单的 \`pageCount\` 与逐页图来自 LibreOffice 转换，可能与 Word
  自己的分页不一致 —— 实测见过一页的 docx 转出两张图、第二张全白。要讲页数先确认
  （docx 的 \`docProps/app.xml\` 里有 \`<Pages>\`，PDF 可以数实际页数），否则不要讲
- **解读不给重点排名**：\`manifest\` 是按路径排的文件清单，不是重要性排序。
  哪个该讲由你读完内容判断，判断依据要说得出（「它定义了全部入口」比「它是枢纽」有说服力）

## 现在能出什么

**解读**（每次调用都会重算）：\`<工作根>/foldercast.json\`。只有机械事实，没有语义判断。

**素材**（默认跑）：\`<工作根>/assets/\`，含 Office / PDF 的逐页图与提取出的全文 Markdown。

**讲稿**：\`<工作根>/script.json\`（你写，校验器查）。

**成片**：显式传 \`render: true\` 时渲染 \`<工作根>/out/video.mp4\`。
同一份讲稿渲染两次**逐帧一致**（画面里没有随机数与时钟）。**渲染慢**：本机实测约 7 帧/秒，
5 分钟的片子要 20 分钟出头，所以不要为了看一眼就整片重渲 —— 调画面用
\`pnpm render <目录> --still <秒>\` 出一张静帧，或 \`--frames A-B\` 出一小段。
没有浏览器时脚本**不替你下载**，会给出三种办法（装 Chrome / \`npx remotion browser ensure\` /
\`FOLDERCAST_BROWSER=<路径>\`），把引导转告用户。

**旁白**：显式传 \`voice: true\` 时先配音再出片。默认 provider 是 macOS 自带的 \`say\`
（免密钥、本地）；换云端音色传 \`ttsProvider: "mimo"\` 并配好 \`MIMO_API_KEY\`。
配音跑过之后画面时间轴来自 \`ffprobe\` 实测的音频时长（不是字数预估），所以换音色会让片长跟着变。

**画面不会因为换音色而变**：同一组时长下换 provider 重渲，产出**逐帧相同**的画面（有测试钉住）。

**改讲稿之后**：\`artifacts\` 里评审、时长表、成片会变成 \`stale\`（旧结论作废、旧音频与旧成片
要重做）。工具不会替你做这件事，也不会自动重渲 —— 按需要再调一次，并显式传 \`voice\` / \`render\`。
`;
